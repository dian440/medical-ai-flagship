def main():
    raw = open(DOC, encoding="utf-8").read()
    applied, missing, already = 0, [], 0
    for old, new in SPLITS:
        if old in raw:
            raw = raw.replace(old, new, 1)
            applied += 1
        elif new in raw:
            already += 1
        else:
            missing.append(old[:60])
    with open(DOC, "w", encoding="utf-8") as f:
        f.write(raw)

    print(f"[拆分] 本次应用 {applied} 处｜此前已应用 {already} 处")
    if missing:
        print(f"[未找到] {len(missing)} 处：")
        for m in missing:
            print("   !", m)

    # 复算中文字符句长
    j = raw.find("## 【中文对照】")
    k = raw.find("## 【数字溯源表】")
    zh = raw[j:k]
    zh_noh = re.sub(r"^#+\s*.*$", "", zh, flags=re.M)
    sents = [s for s in re.split(r"。", zh_noh)
             if len(re.findall(r"[\u4e00-\u9fff]", s)) > 4]
    lens = [len(re.findall(r"[\u4e00-\u9fff]", s)) for s in sents]
    print(f"\n中文句数 {len(lens)}｜中位字数 {int(statistics.median(lens))}｜"
          f"均值 {statistics.mean(lens):.1f}")
    print(f"超 55 字的句子 {sum(1 for x in lens if x>55)}｜"
          f"超 40 字 {sum(1 for x in lens if x>40)}")
    return 0 if not missing else 1


if __name__ == "__main__":
    sys.exit(main())
